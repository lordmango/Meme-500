function appendToJsonFile(filePath, newData) {
    try {
        // Step 1: Read existing file
        let jsonData = [];

        if (fs.existsSync(filePath)) {
            const fileContent = fs.readFileSync(filePath, 'utf8');
            jsonData = fileContent ? JSON.parse(fileContent) : [];
        }

        // Step 2: Ensure it's an array before appending
        if (!Array.isArray(jsonData)) {
            throw new Error("JSON file does not contain an array.");
        }

        // Step 3: Append new data
        jsonData.push(newData);

        // Step 4: Write back to file
        fs.writeFileSync(filePath, JSON.stringify(jsonData, null, 2));

    } catch (error) {
        console.error("Error updating JSON file:", error);
    }
}